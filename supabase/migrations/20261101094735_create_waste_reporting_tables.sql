/*
# Create waste reporting tables

1. New Tables
- `waste_categories`: the ten waste types users can choose from (seeded, unique names).
- `reports`: one row per submitted waste report. `report_number` is generated by the database (WW-YYYY-NNNNNN) from a sequence, so it is unique under concurrent submissions.
- `report_images`: photos linked to a report. Stores the private storage path, not image data.
- `report_status_history`: audit trail of status changes. A trigger writes the initial "reported" entry when a report is inserted.

2. Security
- Row Level Security is enabled on every new table.
- Signed-in users can read categories, read reports and report images (needed by the Active Problems page), and insert their own reports and images.
- Users cannot update or delete reports, images, categories, or history. Status changes are reserved for later phases.
- Status history is readable only for reports the user owns.

3. Important notes
- Idempotent: uses IF NOT EXISTS and DROP POLICY IF EXISTS, so re-running is safe.
- No existing tables or data are modified or dropped.
- The status history trigger runs with elevated rights only to write its own audit row; it is not callable directly.
*/

CREATE TABLE IF NOT EXISTS public.waste_categories (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL,
  description text,
  icon text,
  created_at timestamptz DEFAULT now()
);

