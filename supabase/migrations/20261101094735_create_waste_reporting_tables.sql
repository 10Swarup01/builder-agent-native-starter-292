CREATE SEQUENCE IF NOT EXISTS public.report_number_seq;

CREATE TABLE IF NOT EXISTS public.reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_number text UNIQUE NOT NULL,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  category_id bigint REFERENCES public.waste_categories(id),
  description text,
  quantity text CHECK (quantity IN ('small', 'medium', 'large', 'very_large')),
  duration text,
  blocking_traffic boolean NOT NULL DEFAULT false,
  sensitive_locations text[],
  latitude double precision,
  longitude double precision,
  address text,
  area_id bigint,
  authority_id bigint,
  severity text CHECK (severity IN ('low', 'medium', 'high', 'critical')),
  status text NOT NULL DEFAULT 'reported' CHECK (status IN ('reported', 'classified', 'assigned', 'in_progress', 'resolved', 'rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz
);

CREATE INDEX IF NOT EXISTS reports_user_id_idx ON public.reports (user_id);
CREATE INDEX IF NOT EXISTS reports_status_idx ON public.reports (status);
CREATE INDEX IF NOT EXISTS reports_created_at_idx ON public.reports (created_at DESC);

CREATE TABLE IF NOT EXISTS public.report_images (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  image_url text NOT NULL,
  image_type text CHECK (image_type IN ('original', 'resolution', 'additional')),
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS report_images_report_id_idx ON public.report_images (report_id);

CREATE TABLE IF NOT EXISTS public.report_status_history (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  report_id uuid NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  old_status text,
  new_status text NOT NULL,
  changed_by uuid REFERENCES auth.users(id),
  note text,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS report_status_history_report_id_idx ON public.report_status_history (report_id);

CREATE OR REPLACE FUNCTION public.generate_report_number()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.report_number IS NULL OR NEW.report_number = '' THEN
    NEW.report_number := 'WW-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.report_number_seq')::text, 6, '0');
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_initial_report_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.report_status_history (report_id, old_status, new_status, changed_by, note)
  VALUES (NEW.id, NULL, NEW.status, NEW.user_id, 'Report submitted');
  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.generate_report_number() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.record_initial_report_status() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS reports_generate_number ON public.reports;
CREATE TRIGGER reports_generate_number
  BEFORE INSERT ON public.reports
  FOR EACH ROW EXECUTE FUNCTION public.generate_report_number();

DROP TRIGGER IF EXISTS reports_record_initial_status ON public.reports;
CREATE TRIGGER reports_record_initial_status
  AFTER INSERT ON public.reports
  FOR EACH ROW EXECUTE FUNCTION public.record_initial_report_status();

ALTER TABLE public.waste_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.report_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.report_status_history ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.waste_categories TO authenticated;
GRANT SELECT, INSERT ON public.reports TO authenticated;
GRANT SELECT, INSERT ON public.report_images TO authenticated;
GRANT SELECT ON public.report_status_history TO authenticated;

DROP POLICY IF EXISTS "read_waste_categories" ON public.waste_categories;
CREATE POLICY "read_waste_categories" ON public.waste_categories FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "read_reports" ON public.reports;
CREATE POLICY "read_reports" ON public.reports FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "insert_own_reports" ON public.reports;
CREATE POLICY "insert_own_reports" ON public.reports FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = user_id AND status = 'reported');

DROP POLICY IF EXISTS "read_report_images" ON public.report_images;
CREATE POLICY "read_report_images" ON public.report_images FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "insert_own_report_images" ON public.report_images;
CREATE POLICY "insert_own_report_images" ON public.report_images FOR INSERT
  TO authenticated WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.reports r
      WHERE r.id = report_images.report_id AND r.user_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "read_own_report_history" ON public.report_status_history;
CREATE POLICY "read_own_report_history" ON public.report_status_history FOR SELECT
  TO authenticated USING (
    EXISTS (
      SELECT 1 FROM public.reports r
      WHERE r.id = report_status_history.report_id AND r.user_id = auth.uid()
    )
  );
